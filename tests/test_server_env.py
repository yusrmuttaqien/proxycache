async def main() -> None:
    parser = argparse.ArgumentParser(description="Test script for the server environment")
    parser.add_argument("--test", choices=["concurrent", "n_cache_reuse", "long_conv", "property", "all"],
                        default="all", help="Which test to run")
    args = parser.parse_args()
    
    config = default_config()
    config["upstream"] = UPSTREAM
    config["min_save_tokens"] = 100
    config["max_gb"] = 50.0
    config["control_timeout_ms"] = 60000
    
    client = UpstreamClient(UPSTREAM, api_key=config.get("api_key", ""), timeout_ms=config["control_timeout_ms"])
    state = ProxyState(UPSTREAM, config)
    await state.initialize()
    
    # Save the current chat before the test.
    await save_current_chat(client)
    
    try:
        if args.test in ["concurrent", "all"]:
            await test_concurrent(client, state)
        if args.test in ["n_cache_reuse", "all"]:
            await test_n_cache_reuse(client, state)
        if args.test in ["long_conv", "all"]:
            await test_long_conv(client, state)
        if args.test in ["property", "all"]:
            await test_property(client, state)
    finally:
        # Restore the current chat after the test.
        await restore_current_chat(client)
    
    logger.info("=== Test complete ===")


if __name__ == "__main__":
    asyncio.run(main())
