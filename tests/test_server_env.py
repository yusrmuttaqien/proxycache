async def save_current_chat(client: UpstreamClient) -> None:
    """Save the current conversation (this chat) to disk."""
    logger.info("Saving current chat...")
    result = await client.save_slot(0, f"{CURRENT_CONV}.bin", MODEL)
    if result is None:
        logger.error("Failed to save current chat")
        sys.exit(1)
    logger.info(f"Current chat saved: {result.get('n_written', 0)} bytes")


async def restore_current_chat(client: UpstreamClient) -> None:
    """Restore the current conversation (this chat) from disk."""
    logger.info("Restoring current chat...")
    result = await client.restore_slot(0, f"{CURRENT_CONV}.bin", MODEL)
    if result is None:
        logger.error("Failed to restore current chat")
        sys.exit(1)
    logger.info(f"Current chat restored: {result.get('n_read', 0)} bytes")


